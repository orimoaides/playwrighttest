/**
 * 成果物のダウンロード形式を組み立てる。
 *   - html : manual.inline.html（画像インラインの単一HTML） … server から直接送るので本ファイル対象外
 *   - zip  : manual.html + shots/ + steps.json + scenario.json + routes.json
 *   - site : 複数ページ分割の静的サイト一式（index + step-XX.html + shots/）を zip で
 */

import path from "node:path";
import fs from "node:fs";
import fsp from "node:fs/promises";
import archiver from "archiver";

/**
 * zip 形式: 既存成果物をまとめる。
 * @param {import('./jobs.js').Job} job
 * @param {import('express').Response} res
 */
export function streamZip(job, res) {
  const archive = archiver("zip", { zlib: { level: 9 } });
  res.setHeader("Content-Type", "application/zip");
  res.setHeader("Content-Disposition", `attachment; filename="manual-${job.id}.zip"`);
  archive.on("error", (e) => res.destroy(e));
  archive.pipe(res);

  const f = (n) => path.join(job.dir, n);
  for (const name of ["manual.html", "steps.json", "scenario.json", "routes.json"]) {
    if (fs.existsSync(f(name))) archive.file(f(name), { name });
  }
  const shots = f("shots");
  if (fs.existsSync(shots)) archive.directory(shots, "shots");
  archive.finalize();
}

/**
 * site 形式: 複数ページの静的サイトを生成して zip で返す。
 * @param {import('./jobs.js').Job} job
 * @param {import('express').Response} res
 */
export async function streamSite(job, res) {
  const steps = (job.steps && job.steps.steps) || [];
  const baseUrl = (job.scenario && job.scenario.baseUrl) || "";

  const archive = archiver("zip", { zlib: { level: 9 } });
  res.setHeader("Content-Type", "application/zip");
  res.setHeader("Content-Disposition", `attachment; filename="manual-site-${job.id}.zip"`);
  archive.on("error", (e) => res.destroy(e));
  archive.pipe(res);

  // index.html（目次）
  archive.append(siteIndex(steps, baseUrl), { name: "index.html" });

  // 各ステップページ
  steps.forEach((s, i) => {
    archive.append(sitePage(s, i, steps, baseUrl), { name: `${s.id}.html` });
  });

  // 画像
  const shots = path.join(job.dir, "shots");
  try {
    await fsp.access(shots);
    archive.directory(shots, "shots");
  } catch {
    /* shots 無し */
  }
  archive.finalize();
}

/* ───────── site テンプレート ───────── */

function esc(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

const SITE_CSS = `
  body{font-family:"Hiragino Sans","Noto Sans JP",system-ui,sans-serif;line-height:1.8;color:#20201d;background:#f5f3ed;margin:0}
  .doc{max-width:900px;margin:0 auto;padding:36px 22px 80px}
  a{color:#0b574f}
  h1{font-size:24px;border-bottom:2px solid #0f7268;padding-bottom:12px}
  .toc{list-style:none;padding:0}.toc li{margin:8px 0}
  .toc a{display:block;background:#fff;border:1px solid #e3dfd4;border-radius:10px;padding:12px 16px;text-decoration:none}
  .num{background:#0f7268;color:#fff;width:26px;height:26px;border-radius:50%;display:inline-flex;align-items:center;justify-content:center;font-size:12px;margin-right:8px}
  .badge{font-size:11px;padding:2px 9px;border-radius:999px;font-weight:700}.badge.ok{background:#e6f0ee;color:#0b574f}.badge.err{background:#f7e3df;color:#bb4f3e}
  .action{font-size:14px;color:#4a463d;background:#efece3;padding:8px 12px;border-radius:8px}
  .shots{display:grid;grid-template-columns:1fr 1fr;gap:12px}@media(max-width:620px){.shots{grid-template-columns:1fr}}
  figure{margin:0}img{width:100%;border:1px solid #e3dfd4;border-radius:8px;display:block}figcaption{font-size:12px;color:#6c675d;text-align:center}
  .nav{display:flex;justify-content:space-between;margin-top:24px}
  pre{background:#2a2825;color:#f5f3ed;padding:10px;border-radius:8px;overflow:auto;font-size:12px}
`;

function siteIndex(steps, baseUrl) {
  const items = steps
    .map((s, i) => `<li><a href="${s.id}.html"><span class="num">${i + 1}</span>${esc(s.name)} <span class="badge ${s.status === "ok" ? "ok" : "err"}">${s.status}</span></a></li>`)
    .join("\n");
  return `<!DOCTYPE html><html lang="ja"><head><meta charset="UTF-8"/><meta name="viewport" content="width=device-width, initial-scale=1.0"/>
<title>操作マニュアル — ${esc(baseUrl)}</title><style>${SITE_CSS}</style></head>
<body><div class="doc"><h1>操作マニュアル</h1>
<p>対象: ${esc(baseUrl)} ／ 全 ${steps.length} ステップ</p>
<ul class="toc">${items}</ul>
<footer style="color:#9a958a;font-size:12px;margin-top:24px">Generated by 操作マニュアル自動生成ツール — Phase 2（site形式）</footer>
</div></body></html>`;
}

function sitePage(s, i, steps, baseUrl) {
  const prev = i > 0 ? `<a href="${steps[i - 1].id}.html">← 前へ</a>` : "<span></span>";
  const next = i < steps.length - 1 ? `<a href="${steps[i + 1].id}.html">次へ →</a>` : "<span></span>";
  const logs =
    s.consoleLogs && s.consoleLogs.length ? `<details><summary>ログ (${s.consoleLogs.length})</summary><pre>${esc(s.consoleLogs.join("\n"))}</pre></details>` : "";
  return `<!DOCTYPE html><html lang="ja"><head><meta charset="UTF-8"/><meta name="viewport" content="width=device-width, initial-scale=1.0"/>
<title>${esc(s.name)} — 操作マニュアル</title><style>${SITE_CSS}</style></head>
<body><div class="doc">
<p><a href="index.html">← 目次</a></p>
<h1><span class="num">${i + 1}</span>${esc(s.name)} <span class="badge ${s.status === "ok" ? "ok" : "err"}">${s.status}</span></h1>
<p><a href="${esc(s.url)}" target="_blank" rel="noopener">${esc(s.url)}</a></p>
<p>${esc(s.description)}</p>
<p class="action"><strong>操作:</strong> ${esc(s.action)}</p>
<div class="shots">
  <figure><img src="${esc(s.screenshotBefore)}" alt="操作前"/><figcaption>操作前${s.highlight ? "（赤枠=操作対象）" : ""}</figcaption></figure>
  <figure><img src="${esc(s.screenshotAfter)}" alt="操作後"/><figcaption>操作後</figcaption></figure>
</div>
${logs}
<div class="nav">${prev}${next}</div>
</div></body></html>`;
}
